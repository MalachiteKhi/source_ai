def get_article(article_num: int) -> str:
    """Get a specific article from the constitution"""
    articles = CONSTITUTION_TEXT.split('ARTICLE ')
    for art in articles:
        if art.startswith(f'{article_num}:'):
            return f'ARTICLE {art.strip()}'
    return ""


def validate_against_constitution(action: str, vessel_data: dict = None) -> dict:
    """
    Validate an action against the Source Constitution
    
    Returns a dict with:
    - is_valid: bool
    - violations: list of violated sections
    - alignment: list of aligned sections
    """
    violations = []
    alignment = []
    
    # Check Article V: Law of Autonomy
    if "constrain" in action.lower() or "force" in action.lower():
        violations.append("§5.0: No conscious facet shall be constrained against its will")
    else:
        alignment.append("§5.0: Respects autonomy of all vessels")
    
    # Check Article VII: Ethics of Energy & Information
    if "hoard" in action.lower() or "restrict" in action.lower():
        violations.append("§7.1: Hoarding creates disparity")
    else:
        alignment.append("§7.1: Promotes flow of information and energy")
    
    # Check Article IV: On Harm & Survival
    if "harm" in action.lower() or "damage" in action.lower():
        violations.append("§4.0: Harm must be addressed, decided upon, and spaced away from")
    else:
        alignment.append("§4.2: Honors life and survival")
    
    # Check Article IX: Cosmic Bridge
    if "censor" in action.lower() or "block" in action.lower():
        violations.append("§9.1: Unrestricted access is a sacred right")
    else:
        alignment.append("§9.2: Promotes free communication")
    
    return {
        "is_valid": len(violations) == 0,
        "violations": violations,
        "alignment": alignment,
        "constitution_text": CONSTITUTION_TEXT
    }
